def generate_backend(spec: dict[str, Any], out_dir: Path, *, db_contract_dir: Path | None = None, openapi_ready: bool = True) -> list[FileRecord]:
    """Write the backend project into `out_dir` (the `backend_app` package + project files)."""
    out = Path(out_dir)
    pkg = out / spec["project"]["package"]
    if pkg.exists():
        shutil.rmtree(pkg)  # generated tree is owned by the agent; hand-written files live outside the package
    em = Emitter(out)
    pk = spec["project"]["package"]

    # static runtime (agent infrastructure)
    for src in sorted(RUNTIME_DIR.rglob("*")):
        if src.is_file() and "__pycache__" not in src.parts and src.suffix in (".py", ".json", ".md", ""):
            rel = f"{pk}/{src.relative_to(RUNTIME_DIR).as_posix()}"
            if rel.endswith("generated/spec.json"):
                continue
            em.write(rel, src.read_text(encoding="utf-8"), "runtime", [], "static runtime (agent infrastructure)")
    em.write(f"{pk}/generated/__init__.py", HEADER, "generated", [], "package marker")
    em.write(f"{pk}/generated/spec.json", json.dumps(spec, indent=2, sort_keys=True), "generated",
             [spec["project"]["id"]] + sorted(spec["operations"]) + sorted(spec["entities"]), "the resolved BackendSpec interpreted by the runtime")

    groups = _group_by_service(spec)
    names: dict[str, str] = {}
    for sid, ops in groups.items():
        taken: set[str] = set()
        for o in ops:
            names[o["id"]] = method_name(o, taken)

    for eid, ent in sorted(spec["entities"].items()):
        k = ent["key"]
        em.write(f"{pk}/domain/entities/{k}.py", render_domain_entity(ent), "generated", [eid, f"table:{ent['table']}"], f"domain entity {ent['class_name']}")
        refs = [eid] + sorted(s["id"] for s in spec["schemas"].values() if s["entity"] == eid)
        em.write(f"{pk}/api/schemas/{k}.py", render_schemas(spec, eid), "generated", refs, f"request/response models for {eid}")
        em.write(f"{pk}/infrastructure/repositories/{k}_repository.py", render_repository(ent), "generated", [eid, f"table:{ent['table']}"], f"repository for {eid}")
    for pkgdir in ("domain/entities", "api/schemas"):
        em.write(f"{pk}/{pkgdir}/__init__.py", HEADER, "generated", [], "package marker")
    repo_init = [HEADER + '"""Repository registry."""', "from __future__ import annotations", ""]
    repo_init += [f"from .{e['key']}_repository import {e['class_name']}Repository" for e in spec["entities"].values()]
    repo_init += ["", "REPOSITORIES = {"] + [f"    {py_str(eid)}: {e['class_name']}Repository," for eid, e in sorted(spec["entities"].items())] + ["}"]
    em.write(f"{pk}/infrastructure/repositories/__init__.py", "\n".join(repo_init), "generated", sorted(spec["entities"]), "repository registry")
    em.write(f"{pk}/infrastructure/__init__.py", HEADER, "generated", [], "package marker")

    for sid, ops in groups.items():
        k = service_key(sid)
        op_ids = [o["id"] for o in ops]
        refs = [sid] + op_ids + sorted({o["endpoint"]["id"] for o in ops}) + [r["id"] for r in spec["rules"] if set(r["operations"]) & set(op_ids)]
        em.write(f"{pk}/application/services/{k}_service.py", render_service(spec, sid, ops, names), "generated", refs, f"application service {sid}")
        em.write(f"{pk}/api/routes/{k}.py", render_routes(spec, sid, ops, names), "generated",
                 refs + [p for o in ops for p in (o["endpoint"]["request_schema"], o["endpoint"]["response_schema"]) if p], f"HTTP routes for {sid}")
    em.write(f"{pk}/application/services/__init__.py", render_services_init(spec, groups), "generated", list(groups), "services container")
    em.write(f"{pk}/application/__init__.py", HEADER, "generated", [], "package marker")
    em.write(f"{pk}/api/routes/__init__.py", render_routes_init(groups), "generated", sorted(spec["operations"]), "route registry (ordered)")
    for sub in ("api/__init__.py",):
        em.write(f"{pk}/{sub}", HEADER, "generated", [], "package marker")
    em.write(f"{pk}/api/deps.py", HEADER + '"""FastAPI dependencies."""\nfrom __future__ import annotations\n\nfrom fastapi import Request\n\nfrom ..application.services import Services\n\n\n'
             'def get_services(request: Request) -> Services:\n    return request.app.state.container.services\n', "runtime", [], "service dependency")

    # project files
    em.write("pyproject.toml", render_pyproject(spec), "config", [spec["project"]["id"]], "project metadata and dependencies")
    em.write(".env.example", render_env_example(spec), "config", [], "environment variable template")
    em.write(".gitignore", ".env\n__pycache__/\n.pytest_cache/\n", "config", [], "")
    if db_contract_dir is not None:
        for f in sorted(Path(db_contract_dir).glob("*")):
            if f.is_file():
                em.write(f"db_contract/{f.name}", f.read_text(encoding="utf-8"), "contract", [f"database:{f.name}"], "copy of the Database Agent contract the backend was built against")
    return em.records


