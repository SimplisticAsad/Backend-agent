def render_domain_entity(ent: dict[str, Any]) -> str:
    cls = ent["class_name"]
    lines = [HEADER + f'"""Domain entity {cls} (graph: {ent["id"]}; table: {ent["table"]})."""', "from __future__ import annotations", "",
             "from datetime import date, datetime", "from decimal import Decimal", "from enum import Enum", "from typing import Any, ClassVar", "from uuid import UUID", "",
             "from pydantic import BaseModel, ConfigDict, Field", ""]
    enums = []
    for c in ent["columns"]:
        if c["enum"]:
            ec = cls + snake_to_pascal(c["attr"])
            enums.append((c["attr"], ec))
            lines += ["", f"class {ec}(str, Enum):"] + [f"    {enum_member(v)} = {py_str(v)}" for v in c["enum"]]
    lines += ["", "", f"class {cls}(BaseModel):",
              f'    """Row of `{ent["table"]}` as seen by the domain. Hidden columns are never serialised."""', "",
              '    model_config = ConfigDict(extra="ignore", from_attributes=True)', ""]
    emap = dict(enums)
    for c in ent["columns"]:
        t = emap.get(c["attr"]) or PY_TYPES[c["type"]]
        hidden = c["column"] in ent["hidden_columns"]
        nullable = c["nullable"] or (not c["required"] and c["attr"] != "id")
        ann = f"{t} | None" if nullable else t
        default = " = None" if nullable else ""
        if hidden:
            default = f" = Field({'None' if nullable else '...'}, repr=False, exclude=True)"
        lines.append(f"    {c['attr']}: {ann}{default}")
    lines += ["", f"    TABLE: ClassVar[str] = {py_str(ent['table'])}", f"    GRAPH_ENTITY: ClassVar[str] = {py_str(ent['id'])}"]
    return "\n".join(lines) + "\n"


def _field_decl(f: dict[str, Any], *, request: bool, col: dict[str, Any] | None, enum_name: str | None) -> str:
    ft = parse_field_type(f["type"])
    ann, kw = pydantic_annotation(ft, f.get("enum"), request=request, name=f["name"])
    name = f["name"]
    if request and name == "password":
        ann, kw = "str", [f"max_length={MAX_PASSWORD}", "min_length=1"]
    elif request and name == "new_password":
        ann, kw = "str", [f"max_length={MAX_PASSWORD}", f"min_length={MIN_NEW_PASSWORD}"]
    elif request and name == "reset_token":
        ann, kw = "str", ["max_length=2048", "min_length=1"]
    if ft.base == "decimal":
        ann = "JsonDecimal" if not request else "Decimal"
    if request:
        if f["required"]:
            return f"    {name}: {ann} = Field(..., {', '.join(kw)})" if kw else f"    {name}: {ann}"
        # optional on the wire. If the stored attribute is mandatory, `null` must be rejected (not coerced): keep the plain type.
        non_nullable = bool(col and col["required"])
        typ = ann if non_nullable else f"{ann} | None"
        return f"    {name}: {typ} = Field(None{', ' + ', '.join(kw) if kw else ''})"
    return f"    {name}: {ann}" if f["required"] else f"    {name}: {ann} | None = None"


def render_schemas(spec: dict[str, Any], entity_id: str) -> str:
    ent = spec["entities"][entity_id]
    schemas = [s for s in spec["schemas"].values() if s["entity"] == entity_id]
    cols = {c["attr"]: c for c in ent["columns"]}
    lines = [HEADER + f'"""API request/response models for {ent["id"]} (from api.json schemas)."""', "from __future__ import annotations", "",
             "from datetime import date, datetime", "from decimal import Decimal", "from typing import Any, Literal", "from uuid import UUID", "",
             "from pydantic import BaseModel, ConfigDict, EmailStr, Field", "", "from ...api_common import JsonDecimal", ""]
    auth = spec["auth"]
    for s in sorted(schemas, key=lambda s: s["id"]):
        is_req = s["kind"] == "request"
        lines += ["", "", f"class {s['class_name']}(BaseModel):", f'    """{s["id"]}: {s["name"]}"""', ""]
        lines.append('    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)' if is_req else '    model_config = ConfigDict(from_attributes=True)')
        if not s["fields"]:
            lines.append("    pass")
        for f in s["fields"]:
            lines.append(_field_decl(f, request=is_req, col=cols.get(f["name"]), enum_name=None))
        if is_req:  # server-owned fields: accepted only if equal to the caller, never trusted (see engine._create)
            for op in spec["operations"].values():
                ep = op["endpoint"]
                if ep["request_schema"] == s["id"]:
                    for attr, src in op["params"].get("server_fields", {}).items():
                        if src == "principal.id" and attr not in {f["name"] for f in s["fields"]}:
                            lines.append(f"    {attr}: UUID | None = Field(None, json_schema_extra={{'readOnly': True, 'x-server-owned': True}})")
    if auth and entity_id == auth["entity"] and auth.get("login_response_schema"):
        base = spec["schemas"][auth["login_response_schema"]]["class_name"]
        lines += ["", "", f"class LoginSessionResponse({base}):",
                  '    """Login response satisfying BOTH contracts: the graph\'s user schema (top-level fields) and the Frontend\'s Session {token, user}."""', "",
                  "    token: str", '    token_type: str = "bearer"', "    expires_in: int", f"    user: {base}"]
    for op in spec["operations"].values():
        h = spec["handlers"].get(op["id"])
        if h and h.get("response_extra_fields") and op["entity"] == entity_id:
            resp = spec["schemas"][op["endpoint"]["response_schema"]]["class_name"]
            lines += ["", "", f"class {h['response_class']}({resp}):", f'    """{op["id"]}: additive aggregate fields on top of the graph schema."""', ""]
            for f in h["response_extra_fields"]:
                t = PY_TYPES[f["type"]]
                lines.append(f"    {f['name']}: {t} | None = None")
    return "\n".join(lines) + "\n"


def render_repository(ent: dict[str, Any]) -> str:
    return (HEADER + f'"""Repository for {ent["id"]} over table `{ent["table"]}` (database contract)."""\n'
            "from ...repository import BaseRepository\n\n\n"
            f"class {ent['class_name']}Repository(BaseRepository):\n"
            f"    ENTITY_ID = {py_str(ent['id'])}\n"
            f"    TABLE = {py_str(ent['table'])}\n")


