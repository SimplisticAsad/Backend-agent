def method_name(op: dict[str, Any], taken: set[str]) -> str:
    suffix = op["id"].split(".", 2)[2]
    name = ident(suffix.replace(".", "_"))
    if name in taken:
        name = ident(op["id"].replace(".", "_"))
    taken.add(name)
    return name


def service_key(service_id: str) -> str:
    return service_id.split(".", 1)[1]


def _group_by_service(spec: dict[str, Any]) -> dict[str, list[dict[str, Any]]]:
    out: dict[str, list[dict[str, Any]]] = {}
    for op in spec["operations"].values():
        out.setdefault(op["service"], []).append(op)
    return {k: sorted(v, key=lambda o: o["id"]) for k, v in sorted(out.items())}


def render_service(spec: dict[str, Any], service_id: str, ops: list[dict[str, Any]], names: dict[str, str]) -> str:
    key = service_key(service_id)
    cls = snake_to_pascal(key) + "Service"
    ents = sorted({o["entity"] for o in ops if o["entity"]})
    imports = [HEADER + f'"""Application service {service_id}: one method per graph operation."""', "from __future__ import annotations", "",
               "from datetime import date, datetime, timezone", "from decimal import Decimal", "from typing import Any", "from uuid import UUID", "",
               "from psycopg import sql", "",
               "from ...engine import ListQuery, Page, Principal", "from ...errors import (ConflictError, EntityNotFound, PermissionDenied, ValidationError)",
               "from ...service_base import BaseService"]
    for e in ents:
        k = spec["entities"][e]["key"]
        imports.append(f"from ...domain.entities.{k} import {spec['entities'][e]['class_name']}")
    schema_imports: dict[str, list[str]] = {}
    for o in ops:
        s = o["endpoint"]["request_schema"]
        if s:
            ent = spec["schemas"][s]["entity"]
            schema_imports.setdefault(spec["entities"][ent]["key"], []).append(spec["schemas"][s]["class_name"])
    for k, names_ in sorted(schema_imports.items()):
        imports.append(f"from ...api.schemas.{k} import {', '.join(sorted(set(names_)))}")
    lines = imports + ["", "", f"class {cls}(BaseService):", f'    """Operations of {service_id}. Business rules live in the engine/rules, driven by the graph; routes only delegate here."""', ""]
    for o in ops:
        m = names[o["id"]]
        eid = o["entity"]
        dom = spec["entities"][eid]["class_name"] if eid else "dict"
        req = spec["schemas"][o["endpoint"]["request_schema"]]["class_name"] if o["endpoint"]["request_schema"] else None
        kind, oid = o["kind"], o["id"]
        doc = f'        """{oid} ({o["endpoint"]["method"]} {o["endpoint"]["path"]}) - {o["kind"]}"""'
        if kind == "create":
            lines += [f"    def {m}(self, principal: Principal | None, body: {req}) -> {dom}:", doc,
                      f"        row = self.engine.run({py_str(oid)}, principal, body=body.model_dump(exclude_unset=True))", f"        return {dom}.model_validate(row)", ""]
        elif kind == "read":
            lines += [f"    def {m}(self, principal: Principal | None, row_id: UUID) -> {dom}:", doc,
                      f"        return {dom}.model_validate(self.engine.run({py_str(oid)}, principal, row_id=row_id))", ""]
        elif kind == "list":
            lines += [f"    def {m}(self, principal: Principal | None, query: ListQuery) -> Page:", doc,
                      f"        page = self.engine.run({py_str(oid)}, principal, query=query)",
                      f"        return Page([{dom}.model_validate(r) for r in page.items], page.total)", ""]
        elif kind in ("update", "transition"):
            lines += [f"    def {m}(self, principal: Principal | None, row_id: UUID, body: {req}) -> {dom}:", doc,
                      f"        row = self.engine.run({py_str(oid)}, principal, row_id=row_id, body=body.model_dump(exclude_unset=True))",
                      f"        return {dom}.model_validate(row)", ""]
        elif kind == "delete":
            lines += [f"    def {m}(self, principal: Principal | None, row_id: UUID) -> None:", doc,
                      f"        self.engine.run({py_str(oid)}, principal, row_id=row_id)", ""]
        elif kind == "auth.login":
            lines += [f"    def {m}(self, body: {req}, client: str) -> dict[str, Any]:", doc, "        return self.ctx.auth.login(body.email, body.password, client)", ""]
        elif kind == "auth.logout":
            lines += [f"    def {m}(self, principal: Principal) -> None:", doc, "        self.ctx.auth.logout(principal)", ""]
        elif kind == "auth.request_password_reset":
            lines += [f"    def {m}(self, body: {req}, client: str) -> None:", doc, "        self.ctx.auth.request_password_reset(body.email, client)", ""]
        elif kind == "auth.reset_password":
            lines += [f"    def {m}(self, body: {req}, client: str) -> None:", doc, "        self.ctx.auth.reset_password(body.reset_token, body.new_password, client)", ""]
        else:  # custom / aggregate
            h = spec["handlers"].get(oid)
            lines.append(f"    def {m}(self, principal: Principal | None, *, row_id: UUID | None = None, body: dict[str, Any] | None = None, query: ListQuery | None = None) -> Any:")
            lines.append(doc)
            if h and h.get("status") == "implemented":
                lines.append(f"        # handler source: {h.get('source', 'llm')} ({h.get('stage', 'api_implementation')})")
                lines += ["        " + ln if ln.strip() else "" for ln in h["code"].rstrip().splitlines()]
            else:
                lines.append(f"        return self.not_implemented({py_str(oid)})")
            lines.append("")
    return "\n".join(lines) + "\n"


def _path_sort_key(path: str) -> tuple:
    return tuple((1, "") if seg.startswith("{") else (0, seg) for seg in path.strip("/").split("/"))


def _py_query_type(q: dict[str, Any]) -> str:
    if q["enum"]:
        return "Literal[" + ", ".join(py_str(v) for v in q["enum"]) + "]"
    return PY_TYPES[q["type"]]


def render_routes(spec: dict[str, Any], service_id: str, ops: list[dict[str, Any]], names: dict[str, str]) -> str:
    key = service_key(service_id)
    ents = sorted({o["entity"] for o in ops if o["entity"]})
    head = [HEADER + f'"""HTTP routes for {service_id}. Route handlers only delegate to the application service."""', "from __future__ import annotations", "",
            "from datetime import date, datetime", "from decimal import Decimal", "from typing import Any, Literal", "from uuid import UUID", "",
            "from fastapi import APIRouter, Depends, Query, Request, Response", "",
            "from ...api_common import error_responses", "from ...auth import authorize", "from ...engine import ListQuery, Principal",
            "from ..deps import get_services", "from ...application.services import Services"]
    schema_imports: dict[str, set[str]] = {}
    for o in ops:
        ep = o["endpoint"]
        for sid in (ep["request_schema"], ep["response_schema"]):
            if sid:
                schema_imports.setdefault(spec["entities"][spec["schemas"][sid]["entity"]]["key"], set()).add(spec["schemas"][sid]["class_name"])
        h = spec["handlers"].get(o["id"])
        if h and h.get("response_class") and o["entity"]:
            schema_imports.setdefault(spec["entities"][o["entity"]]["key"], set()).add(h["response_class"])
        if o["kind"] == "auth.login":
            schema_imports.setdefault(spec["entities"][o["entity"]]["key"], set()).add("LoginSessionResponse")
    for k, n in sorted(schema_imports.items()):
        head.append(f"from ..schemas.{k} import {', '.join(sorted(n))}")
    lines = head + ["", f"router = APIRouter(tags=[{py_str(key)}])", ""]
    for o in sorted(ops, key=lambda o: (_path_sort_key(o["endpoint"]["path"]), o["endpoint"]["method"])):
        ep, oid = o["endpoint"], o["id"]
        m = names[oid]
        kind = o["kind"]
        resp_cls = None
        if ep["response_schema"]:
            resp_cls = spec["schemas"][ep["response_schema"]]["class_name"]
        h = spec["handlers"].get(oid)
        if h and h.get("response_class"):
            resp_cls = h["response_class"]
        if kind == "auth.login":
            resp_cls = "LoginSessionResponse"
        many = o["cardinality"] == "many"
        resp_model = "None" if (ep["status_code"] == 204 or not resp_cls) else (f"list[{resp_cls}]" if many else resp_cls)
        params = ["request: Request"]
        call_args = ["principal"]
        if kind.startswith("auth."):
            call_args = []
        if "id" in ep["path_params"]:
            params.append("id: UUID")
        if ep["request_schema"]:
            params.append(f"body: {spec['schemas'][ep['request_schema']]['class_name']}")
        is_list = kind == "list" or (kind == "aggregate" and many)
        if is_list:
            params.append("response: Response")
            for q in ep["query_params"]:
                if q["kind"] == "filter":
                    params.append(f"{q['name']}: {_py_query_type(q)} | None = None")
                else:
                    params.append("query: str | None = Query(None, max_length=200, description=\"Case-insensitive text search\")")
            params += ["limit: int = Query(100, ge=1, le=1000)", "offset: int = Query(0, ge=0)",
                       "sort: str | None = Query(None, max_length=64, description=\"Attribute to sort by\")",
                       "order: Literal['asc', 'desc'] = Query('asc')"]
        auth_dep = "Depends(authorize(" + py_str(oid) + "))"
        public = o["access"] == "public"
        params.append(f"principal: Principal | None = {auth_dep}" if not public else f"principal: None = {auth_dep}")
        params.append("services: Services = Depends(get_services)")
        svc = f"services.{key}.{m}"
        client = "request.client.host if request.client else 'unknown'"
        body = []
        if kind.startswith("auth."):
            args = []
            if ep["request_schema"]:
                args.append("body")
            if kind != "auth.logout":
                args.append(client)
            else:
                args = ["principal"]
            call = f"{svc}({', '.join(args)})"
            body = [f"    return {call}"] if ep["status_code"] != 204 else [f"    {call}", "    return Response(status_code=204)"]
        elif kind in ("create",):
            body = [f"    return {svc}(principal, body)"]
        elif kind in ("read",):
            body = [f"    return {svc}(principal, id)"]
        elif kind in ("update", "transition"):
            body = [f"    return {svc}(principal, id, body)"]
        elif kind == "delete":
            body = [f"    {svc}(principal, id)", "    return Response(status_code=204)"]
        elif kind == "list":
            filt = ", ".join(f"{q['name']!r}: {q['name']}" for q in ep["query_params"] if q["kind"] == "filter")
            qarg = "query" if any(q["kind"] == "search" for q in ep["query_params"]) else "None"
            body = [f"    page = {svc}(principal, ListQuery(filters={{{filt}}}, search={qarg}, sort=sort, order=order, limit=limit, offset=offset))",
                    "    response.headers['X-Total-Count'] = str(page.total)", "    return page.items"]
        else:  # custom / aggregate
            kw = []
            if "id" in ep["path_params"]:
                kw.append("row_id=id")
            if ep["request_schema"]:
                kw.append("body=body.model_dump(exclude_unset=True)")
            if is_list:
                filt = ", ".join(f"{q['name']!r}: {q['name']}" for q in ep["query_params"] if q["kind"] == "filter")
                kw.append(f"query=ListQuery(filters={{{filt}}}, sort=sort, order=order, limit=limit, offset=offset)")
            call = f"{svc}(principal{', ' if kw else ''}{', '.join(kw)})"
            if ep["status_code"] == 204:
                body = [f"    {call}", "    return Response(status_code=204)"]
            elif many:
                body = [f"    result = {call}", "    items = result.items if hasattr(result, 'items') and not isinstance(result, dict) else result",
                        "    if hasattr(result, 'total'):", "        response.headers['X-Total-Count'] = str(result.total)", "    return items"]
            else:
                body = [f"    return {call}"]
        desc = (o["description"] or o["name"]) + f"\n\nOperation `{oid}`. Access: {o['access']}" + (f" ({', '.join(r.split('.', 1)[1] for r in o['roles'])})" if o["roles"] else "") + "."
        if o["notes"]:
            desc += " Note: " + "; ".join(o["notes"])
        er = (f"error_responses(authenticated={not public}, restricted={o['access'] == 'restricted'}, has_path_id={'id' in ep['path_params']}, "
              f"mutating={ep['method'] != 'GET'}, rate_limited={kind.startswith('auth.') and public})")
        lines += [
            f"@router.{ep['method'].lower()}({py_str(ep['path'])}, operation_id={py_str(ep['id'])}, summary={py_str(o['name'])}, description={py_str(desc)},",
            f"    response_model={resp_model}, status_code={ep['status_code']}, responses={er}" + (", response_class=Response" if ep["status_code"] == 204 else "") + ")",
            f"def {ident(ep['id'].replace('.', '_'))}({', '.join(params)}):"] + body + [""]
    return "\n".join(lines) + "\n"


def render_services_init(spec: dict[str, Any], groups: dict[str, list[dict[str, Any]]]) -> str:
    lines = [HEADER + '"""Application services container."""', "from __future__ import annotations", "", "from ...service_base import ServiceContext"]
    for sid in groups:
        k = service_key(sid)
        lines.append(f"from .{k}_service import {snake_to_pascal(k)}Service")
    lines += ["", "", "class Services:", '    """One attribute per graph service."""', "", "    def __init__(self, ctx: ServiceContext) -> None:"]
    lines += [f"        self.{service_key(sid)} = {snake_to_pascal(service_key(sid))}Service(ctx)" for sid in groups] or ["        pass"]
    lines += ["", "", "def build_services(ctx: ServiceContext) -> Services:", "    return Services(ctx)"]
    return "\n".join(lines) + "\n"


def render_routes_init(groups: dict[str, list[dict[str, Any]]]) -> str:
    lines = [HEADER + '"""All routers combined into one, routes ordered most-specific first.', "",
             'FastAPI matches in registration order, so `/tasks/assigned` must precede `/tasks/{id}`; sorting globally guarantees it."""',
             "from __future__ import annotations", "", "from fastapi import APIRouter", ""]
    for sid in groups:
        k = service_key(sid)
        lines.append(f"from .{k} import router as {k}_router")
    lines += ["", "", "def _key(route) -> tuple:", '    segs = route.path.strip("/").split("/")', "    return tuple((1, '') if s.startswith('{') else (0, s) for s in segs)", "",
              "", "api_router = APIRouter()", "_routes = [r for rt in [" + ", ".join(f"{service_key(s)}_router" for s in groups) + "] for r in rt.routes]",
              "api_router.routes.extend(sorted(_routes, key=lambda r: (_key(r), sorted(getattr(r, 'methods', []) or []))))", "", "ROUTERS = [api_router]"]
    return "\n".join(lines) + "\n"


