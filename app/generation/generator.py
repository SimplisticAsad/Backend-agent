"""Backend code generator.

Renders the graph-specific modules (domain entities, API schemas, repositories, services, routes) from a BackendSpec and
copies the static runtime (`runtime/backend_app`). Deterministic: same spec -> byte-identical output.

Every emitted file is recorded in a `FileRecord` with the specification IDs it implements (file_manifest.json).
"""
from __future__ import annotations

import hashlib
import json
import keyword
import re
import shutil
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from app.analysis.typesys import MAX_PASSWORD, MIN_NEW_PASSWORD, parse_field_type, pydantic_annotation
from app.graph.model import snake_to_pascal

RUNTIME_DIR = Path(__file__).parent / "runtime" / "backend_app"
HEADER = '# GENERATED by the Backend Agent from the project graphs. Do not edit by hand: regenerate instead.\n'
PY_TYPES = {"uuid": "UUID", "string": "str", "text": "str", "email": "str", "url": "str", "integer": "int", "decimal": "Decimal",
            "boolean": "bool", "date": "date", "datetime": "datetime", "json": "Any"}


@dataclass
class FileRecord:
    path: str
    kind: str  # generated | runtime | config | test | contract
    source_refs: list[str] = field(default_factory=list)
    sha256: str = ""
    description: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {"path": self.path, "kind": self.kind, "source_refs": sorted(set(self.source_refs)), "sha256": self.sha256, "description": self.description}


class Emitter:
    def __init__(self, root: Path) -> None:
        self.root, self.records = root, []

    def write(self, rel: str, content: str, kind: str, refs: list[str] | None = None, description: str = "") -> None:
        path = self.root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        if not content.endswith("\n"):
            content += "\n"
        path.write_text(content, encoding="utf-8")
        self.records.append(FileRecord(rel, kind, list(refs or []), hashlib.sha256(content.encode()).hexdigest(), description))


def ident(name: str) -> str:
    n = re.sub(r"[^0-9a-zA-Z_]", "_", name)
    if n[:1].isdigit():
        n = "v_" + n
    return n + "_" if keyword.iskeyword(n) else n


def enum_member(value: str) -> str:
    return ident(value).upper()


def py_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


